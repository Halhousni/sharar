#!/usr/bin/env python3
"""The string-table resources (RT_STRING) of Spike2's executable, as a Rust table: the lifted
code loads its messages (Error$ and the dialogs' texts) by number.

    tools/dump_strings.py vmbin/SONVIEW.exe vmbin/spikecmd.dll vmbin/compiler.dll vmbin/SpikeUtl.dll s2lift/src/strings_gen.rs
"""
import struct, sys
sys.path.insert(0, __import__("os").path.dirname(__file__))
from command_table import Image
from lift import write_if_changed

def strings(path):
    im = Image(path)
    d = im.b
    rsrc = next(s for s in im.secs if s[0] == b".rsrc")
    base_off, base_va = rsrc[3], rsrc[1]

    def entries(off):
        named, ids = struct.unpack_from("<HH", d, off + 12)
        return [struct.unpack_from("<II", d, off + 16 + 8 * i) for i in range(named + ids)]

    out = {}
    for tid, to in entries(base_off):
        if tid != 6:
            continue
        for bid, bo in entries(base_off + (to & 0x7fffffff)):
            for lang, lo in entries(base_off + (bo & 0x7fffffff)):
                rva, size, _, _ = struct.unpack_from("<IIII", d, base_off + lo)
                p = base_off + rva - base_va
                for k in range(16):
                    n, = struct.unpack_from("<H", d, p)
                    if n:
                        out[(bid - 1) * 16 + k] = d[p + 2:p + 2 + 2 * n].decode("utf-16le")
                    p += 2 + 2 * n
    return out

if __name__ == "__main__":
    t = {}
    for path in sys.argv[1:-1]:
        for k, v in strings(path).items():
            t.setdefault(k, v)
    lines = ["//! Generated by tools/dump_strings.py from the string tables of Spike2's modules (the application first). Do not edit.", "",
             "pub static STRINGS: &[(u32, &str)] = &["]
    def lit(x):
        return '"' + "".join("\\" + c if c in '"\\' else f"\\u{{{ord(c):x}}}" if ord(c) < 32 or ord(c) == 127 else c for c in x) + '"'
    for k in sorted(t):
        lines.append(f"    ({k}, {lit(t[k])}),")
    lines.append("];")
    write_if_changed(sys.argv[-1], ("\n".join(lines) + "\n").encode())
    print(len(t), "strings")
